def check(rec):
    n = 0
    for blk in ("setting", "shown", "limits", "supp"):
        for item in rec.get(blk, []):
            page, sec, q = item[:3]
            mode = item[3] if len(item) > 3 else "text"
            supp = blk == "supp"
            if mode == "layout":
                hay = layout_text(rec["supp_pdf"] if supp else rec["pdf"], page)
            else:
                hay = page_text(rec["supp_txt"] if supp else rec["txt"], page)
            if norm(q) not in hay:
                sys.exit(f"{rec['key']}: not found on p.{page} ({mode}{', supplement' if supp else ''}): {q[:90]!r}")
            n += 1
    return n


