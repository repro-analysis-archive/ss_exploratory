def norm(s):
    s = s.replace("­", "").replace("ﬁ", "fi").replace("ﬂ", "fl")
    return re.sub(r"\s+", " ", s).strip()


def page_text(txt, page):
    pages = open(os.path.join(FT, txt), encoding="utf-8", errors="replace").read().split("\f")
    return norm(pages[page - 1])


def layout_text(pdf, page):
    out = subprocess.run(["pdftotext", "-layout", "-f", str(page), "-l", str(page), os.path.join(FT, pdf), "-"],
                         capture_output=True, text=True, check=True).stdout
    return norm(out)


